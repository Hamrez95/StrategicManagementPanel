import fs from 'node:fs';
import ts from 'typescript';
const data = JSON.parse(
  fs.readFileSync('apps/web/src/features/experience/design-research.json', 'utf8'),
);
const js = ts.transpileModule(
  fs.readFileSync('apps/web/src/features/experience/planningDesigns.ts', 'utf8'),
  { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext } },
).outputText;
const { planningDesigns } = await import(
  `data:text/javascript;base64,${Buffer.from(js).toString('base64')}`
);
const counts = data.inventory.reduce(
  (out, r) => ({ ...out, [r.kind]: (out[r.kind] || 0) + 1 }),
  {},
);
const md = `# Research → UI coverage — 2026-10-17

Generated by scripts/report-design-coverage.mjs from the exact catalog projection and authored planning definitions. This is design coverage, not scientific/runtime completion.

**${data.entries.length} dedicated researched method pages** (${counts.frameworks} frameworks and ${counts.metrics} metrics), **${planningDesigns.length} authored planning flows**, plus the existing eight local tools. The directory exposes ${data.domains.length} taxonomy domains and a six-part navigation from direction through review. Every one of the ${data.inventory.length} indexed research records has a declared disposition below. Canonical research files and immutable runtime releases were not changed.

## What is ready

- Shared calm directory/roadmap, search/category/type filters, direct method routes, per-Workspace question drafts, progress/resume and readable review layouts.
- Vision, mission, purpose, values, goals/governance; marketing STP, 4Ps, brand, channels, marketing plan/campaign, sales pipeline; strategic choice and control; authored layouts for TOWS, QSPM, CPM, SPACE, IE, Ansoff and Grand Strategy.
- Dedicated routes for all 33 existing frameworks, including VRIO, PESTEL, Five Forces, value chain, BCG, GE, BSC, Hoshin, OKR, RACI, MoSCoW, BMC, VPC, JTBD, Lean Startup, RICE, North Star, cohorts, Lean/TOC/DMAIC, 7S, Kotter, psychological safety, risk/financial workflows and NIST AI RMF.
- All 31 metric pages have scoped data collection, source explanations, limits and a result-contract layout. Numeric/date/currency/series controls and observed/estimate/unknown/not-applicable choices are designed. NPV/IRR/LTV series have repeatable period/amount rows. BMC has nine separate content blocks plus an evidence card.
- Existing IFE/EFE and 13 finance previews retain actual local calculations. **The newly exposed advanced method/metric pages save design drafts; their verified calculation services and automatic diagnoses are not implemented.** A source formula is displayed as text, never executed with eval. Portfolio plots do not display invented positions.

## What is not complete

The research foundation's STATUS.md explicitly marks marketing attribution/brand/channel detail, market sizing/sampling, TOWS/Ansoff extensions, leadership/HR, transformation and local finance as partially researched or pending. Authored UI templates cover the editing experience but do not fill those scientific gaps. The new OpenStax direction/STP/4Ps/marketing-plan references are educational design references, not a curated runtime release. There is no claim that all possible concepts in strategic management have been researched, implemented or validated.

The ten diagnostic trees, eleven rules, eight recommendations/actions/anti-patterns and eleven terms remain contextual research references pending engine integration. They are not activated as automatic advice simply to make a checklist green. Real API persistence, permissions, revisions, canonical bindings and scientific method promotion remain with the Luna packets. Server/PostgreSQL, Docker and physical validation stay at the end.

## Authored planning pages

| Page | Domain | Route | State |
| --- | --- | --- | --- |
${planningDesigns.map((d) => `| ${d.title} | ${d.area} | tool/${d.id} | UI draft ready; canonical service/research review pending |`).join('\n')}

## Every researched framework and metric

| Exact record | Page | Domain | Source file | Runtime |
| --- | --- | --- | --- | --- |
${data.entries.map((r) => `| ${r.id} | ${r.title} | ${r.domain} | [source](../../assets/management-knowledge/${r.sourcePath}) | UI draft ready; verified adapter pending |`).join('\n')}

Each row has route research/<exact-record-id>. IDs, input order and step keys are stable in design-research.json. UI Persian translations preserve source IDs and limits; the nine-block BMC is an authored presentation adapter. Source aliases resolve to canonical bibliography IDs.

## Coverage disposition by research record kind

| Kind | Count | Actual disposition |
| --- | --- | --- |
${Object.entries(counts)
  .map(
    ([kind, count]) =>
      `| ${kind} | ${count} | ${['frameworks', 'metrics'].includes(kind) ? 'Dedicated input/review design page' : kind === 'sources' ? 'Attribution and depth metadata; not proof of efficacy' : 'Contextual reference; runtime integration pending'} |`,
  )
  .join('\n')}

## Source depth and scope

The 68-source bibliography includes abstracts/excerpts as well as fuller text. The UI does not upgrade access depth, validity or applicability. Taxonomy coverage is a product organization scheme, not a universal management ontology. See [LUNA_COMPLETE_DESIGN_PACKETS](LUNA_COMPLETE_DESIGN_PACKETS.md) for exact implementation boundaries.
`;
const target = 'docs/management-os/RESEARCH_UI_COVERAGE.md';
if (process.argv.includes('--check')) {
  if (fs.readFileSync(target, 'utf8') !== md) throw new Error('Coverage report drift');
} else fs.writeFileSync(target, md);
console.log(
  `${data.entries.length} researched pages, ${planningDesigns.length} planning flows, ${data.domains.length} domains; coverage report generated.`,
);
